#!/usr/bin/env bash
# Print a CLI config (promcost.yaml) for this env on stdout: the forwarded
# gateway as backend, and an inventory whose replica counts are read from
# the cluster as it is right now - so re-run it after scaling.
#
# Prices are ILLUSTRATIVE (a staging box has no invoice): every pool is
# priced at the same per-replica figure so currency shares are easy to
# eyeball against resource shares. Replace them for anything real.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

# Replicas of a component, summed across its zone-aware StatefulSets or
# its Deployment.
replicas() {
  kubectl -n "$MIMIR_NS" get deploy,statefulset -l "app.kubernetes.io/component=$1" \
    -o jsonpath='{range .items[*]}{.spec.replicas}{"\n"}{end}' | awk '{s+=$1} END {print s+0}'
}

cat <<YAML
# Generated by dev/staging/scripts/promcost-config.sh at $(date -u +%FT%TZ)
# against $(kubectl config current-context). Prices are illustrative.
backend:
  url: http://127.0.0.1:$MIMIR_PORT
  timeout: 2m
inventory:
  currency: EUR
  pools:
    ingester_memory:
      replicas: $(replicas ingester)
      cost_per_replica_month: 120
    query_path:
      components:
        query-frontend:
          replicas: $(replicas query-frontend)
          cost_per_replica_month: 40
        querier:
          replicas: $(replicas querier)
          cost_per_replica_month: 60
    ruler_cpu:
      replicas: $(replicas ruler)
      cost_per_replica_month: 60
YAML
