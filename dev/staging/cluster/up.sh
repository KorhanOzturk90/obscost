#!/usr/bin/env bash
# Create the local single-node cluster: plain k3s in a Docker container.
#
# Not k3d: k3d's tools image comes from ghcr.io, which the cloud
# container's network policy denies. Plain k3s needs nothing but its own
# image. On a laptop with k3d, or on a real cluster, skip this entirely and
# run `make deploy` with KUBECONFIG pointing at that cluster.
set -euo pipefail
cd "$(dirname "$0")"
source ./lib.sh

: "${K3S_IMAGE:=rancher/k3s:v1.33.4-k3s1}" "${STATE:=$PWD/../.state}"
API_PORT=${API_PORT:-6445}
mkdir -p "$STATE"

docker info >/dev/null 2>&1 || {
  echo "Docker is not running. In the cloud container: dockerd > /tmp/dockerd.log 2>&1 &" >&2
  exit 1
}

if ! docker container inspect "$NODE" >/dev/null 2>&1; then
  host_pull "$(canonical "$K3S_IMAGE")"
  log "starting $NODE ($K3S_IMAGE)"
  # Traefik and metrics-server are k3s add-ons, not part of the
  # environment being modelled. /var/lib/rancher/k3s on a volume keeps
  # images and PVs across a container restart.
  #
  # Kubelet disk thresholds are absolute, not percentages: the cloud
  # container's filesystem reports 252 GB but only ~30 GB of it is ours, so
  # the default percentages read it as >85% full. Image GC then deletes
  # every preloaded image no pod is using at that moment (the pause image
  # included, which no registry can re-supply from inside the node), and
  # eviction follows.
  #
  # `mount --make-rshared /` (what k3d's entrypoint does): node-exporter
  # mounts the host root with HostToContainer propagation, which needs /
  # to be a shared mount. Done in the entrypoint so it survives restarts.
  docker run -d --name "$NODE" --hostname "$NODE" --privileged \
    --tmpfs /run --tmpfs /var/run \
    -v "$NODE-data:/var/lib/rancher/k3s" \
    -p "127.0.0.1:$API_PORT:6443" \
    --restart unless-stopped \
    --entrypoint /bin/sh \
    "$(canonical "$K3S_IMAGE")" -c 'mount --make-rshared / && exec /bin/k3s "$@"' k3s server \
    --disable traefik --disable metrics-server \
    --kubelet-arg=image-gc-high-threshold=100 --kubelet-arg=image-gc-low-threshold=99 \
    '--kubelet-arg=eviction-hard=nodefs.available<2Gi,imagefs.available<2Gi' \
    --tls-san 127.0.0.1 --write-kubeconfig-mode 644 >/dev/null
elif [[ $(docker inspect -f '{{.State.Running}}' "$NODE") != true ]]; then
  docker start "$NODE" >/dev/null
fi

for _ in $(seq 90); do
  docker exec "$NODE" test -s /etc/rancher/k3s/k3s.yaml 2>/dev/null && break
  sleep 2
done
docker exec "$NODE" cat /etc/rancher/k3s/k3s.yaml |
  sed -e "s#https://127.0.0.1:6443#https://127.0.0.1:$API_PORT#" -e "s#: default#: $CLUSTER#" \
  > "$STATE/kubeconfig"
export KUBECONFIG=$STATE/kubeconfig

# The cloud container drops CAP_SYS_RESOURCE, so no process in it - the
# k3s node included - can lower its oom_score_adj. The kubelet asks for
# -998 on every pod sandbox, and runc then fails every pod with "can't get
# final child's PID from pipe: EOF". containerd's restrict_oom_score_adj
# (made for rootless setups) clamps requests to what is allowed instead.
# Only applied where the capability is actually missing.
tmpl=/var/lib/rancher/k3s/agent/etc/containerd/config.toml.tmpl
if ! docker exec "$NODE" sh -c 'echo -1 > /proc/self/oom_score_adj' 2>/dev/null &&
  ! docker exec "$NODE" test -f "$tmpl"; then
  log "node cannot lower oom_score_adj; setting containerd restrict_oom_score_adj and restarting k3s"
  for _ in $(seq 60); do
    docker exec "$NODE" test -s /var/lib/rancher/k3s/agent/etc/containerd/config.toml && break
    sleep 2
  done
  docker exec "$NODE" sh -c "sed -e '/^# File generated by k3s/d' \
    -e \"s/^\\[plugins.'io.containerd.cri.v1.runtime'\\]\$/&\\n  restrict_oom_score_adj = true/\" \
    /var/lib/rancher/k3s/agent/etc/containerd/config.toml > $tmpl"
  docker exec "$NODE" grep -q restrict_oom_score_adj "$tmpl" || { echo "could not patch containerd config" >&2; exit 1; }
  docker restart "$NODE" >/dev/null
  sleep 5
fi

# k3s's own images: the pause sandbox, and whatever its add-ons run.
sandbox=$(docker exec "$NODE" sh -c 'grep -h "sandbox" /var/lib/rancher/k3s/agent/etc/containerd/config*.toml 2>/dev/null' | sed -n 's/.*"\(.*\)".*/\1/p' | head -1)
until kubectl get nodes >/dev/null 2>&1; do sleep 2; done
for _ in $(seq 60); do
  addons=$(kubectl get pods -A -o jsonpath='{.items[*].spec.containers[*].image}' 2>/dev/null || true)
  [[ $addons == *coredns* ]] && break
  sleep 2
done
helper=$(kubectl -n kube-system get cm local-path-config -o jsonpath='{.data.helperPod\.yaml}' 2>/dev/null | sed -n 's/.*image: *"\{0,1\}\([^" ]*\)"\{0,1\}/\1/p')
preload ${sandbox:-rancher/mirrored-pause:3.6} $addons ${helper:-rancher/mirrored-library-busybox:1.36.1}

kubectl wait --for=condition=Ready node --all --timeout=180s >/dev/null
kubectl -n kube-system rollout status deploy/coredns --timeout=180s >/dev/null
kubectl -n kube-system rollout status deploy/local-path-provisioner --timeout=180s >/dev/null
echo "cluster $CLUSTER-k3s ready: $(kubectl get nodes --no-headers | awk '{print $1, $2, $5}')"
